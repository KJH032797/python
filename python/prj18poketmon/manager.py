def select_user_poketmon():
    global user
    while True:
        num = int(input("Choose Poketmon Number: "))
        match num:
            case 1:
                user = Pikachu()
            case 2:
                user = Lizard()
            case 3:
                user = Turtle()
            case _:
                print("Wrong choice. Please try again.")
                continue
        break

def select_com_poketmon():
    global com
    num = random.randint(1, 3)
    match num:
        case 1:
            com = Pikachu()
        case 2:
            com = Lizard()
        case 3:
            com = Turtle()

def attack(attacker, defender, num):
    # 동작 수행
    match num:
        case 1:
            attacker.tackle(defender)
        case 2:
            attacker.skill(defender)

    #정보출력
    print("\nattacker", attacker)
    print("defender", defender)

    #결과 판단
    result = defender.is_dead()
    if result:
        print(f"🎉{attacker.name}의 승 리 ! ! !🎉")
        return True

def battle_start():
    while True:
        # 사용자 턴
        if user.is_burned :
            print(f"{user.name}가 불타오릅니다!")
            user.hp -= 4
            user.is_burned = False

        if user.is_stunned :
            print(f"{user.name}가 감전되어 행동할 수 없습니다!")
            user.is_stunned = False

        else :
            print("\n----- Choose your Action -----")
            print(1, "몸통박치기")
            print(2, "스킬")
            num = int(input("Choose Action Number: "))
            is_finish = attack(attacker=user, defender=com, num=num)
            if is_finish: break

        # 컴퓨터 턴
        if com.is_burned :
            print(f"{com.name}가 불타오릅니다!")
            com.hp -= 4
            com.is_burned = False

        if com.is_stunned :
            print(f"{com.name}가 감전되어 행동할 수 없습니다!")
            com.is_stunned = False

        else :
            num = random.randint(1, 2)
            is_finish = attack(attacker=com, defender=user, num=num)
            if is_finish: break

